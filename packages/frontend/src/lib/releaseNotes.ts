/**
 * 「这个版本做了什么」：版本号 → 给人看的说明条目。
 *
 * 唯一用途：给 AppVersion 的问号提示供文字，鼠标移入或点击时显示。
 *
 * 只写使用者在自己页面上看得到的变化（龚成 2026-11-05 定档）：只有管理员能看到的
 * 内容一律不进这里，含用户管理那张表的改动、系统设置里的改动、以及升级流程本身。
 * 高级用户在自己页面上选得到的东西算使用者能看到的，要写。
 * 按这条筛完某个版本可能一条不剩，那就把这个键整个删掉，让该版本不显示问号，不留空壳。
 *
 * 为什么按版本分开存，而不是只留一份最新的：同一条东西在不同版本上叫法不一样，
 * 混成一份会让旧版本的页面说出新版本才有的名字。
 *
 * 为什么对不上就不显示：版本号来自实际安装的那包（deploy/.env 的 IMAGE_TAG），
 * 说明文字来自这里。两边对不上时，宁可没有问号，也不能拿别的版本的说明糊到当前
 * 页面上——这跟 AGENTS.md 规则 9「禁止假控件」是同一口径：界面上摆出来的东西必须真对得上。
 *
 * 发版时怎么加：在下面追加一条，键名照 deploy/.env 的 IMAGE_TAG 写（不带 v 前缀）。
 * 措辞照 AGENTS.md 规则 11：规范书面语，不出现只有开发者才懂的词，界面名称用「」，
 * 不写数据库行号、随机 ID、服务器路径、英文原值。每条都要能指回一次真实改动。
 */

export interface ReleaseNote {
  /** 提示框标题 */
  heading: string;
  /** 逐条说明，每条一句话说清一项变化，按重要程度排，不加补充解释 */
  items: string[];
}

const HEADING = '这个版本做了什么';

const NOTES: Record<string, ReleaseNote> = {
  '0.7.1': {
    heading: HEADING,
    items: [
      '创建生成任务时「生成方式」带产品名称',
      '全局用量统一使用「积分」表示',
      '创建生成任务弹窗样式改进',
      'PPT Master 6.6 版「生成方式」支持材料发散度、阅读模式、是否允许上网补充素材、主语言、配图来源、受众、沟通意图、核心信息等高级用户可选参数',
      '「内容风格」等四项设置按界面上选定的执行',
      '生成失败时按原因分别提示，不再统一显示「请重试」',
      '修改页面后「保存为新版本」不再报错',
      '升级后旧草稿提交不再失败',
      '未编辑的空白页自动去掉占位提示文字',
    ],
  },
};

/** 去掉 v 前缀和首尾空格，让 "v0.6.4" 和 "0.6.4" 认成同一个版本。 */
function normalize(version: string): string {
  return version.trim().replace(/^v/i, '');
}

/**
 * 取当前版本的说明。开发态没有版本号（后端返回 null）或版本对不上时返回 null，
 * 调用方据此不渲染问号。
 */
export function releaseNoteFor(version: string | null | undefined): ReleaseNote | null {
  if (!version) return null;
  return NOTES[normalize(version)] ?? null;
}
